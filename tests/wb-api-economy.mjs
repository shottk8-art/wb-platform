import assert from 'node:assert/strict';
import {advertising,economy} from '../supabase/functions/wb-api/economy.ts';
const ads=advertising({'Баланс':{amount:'100.10'},'Счёт':{amount:20},'Кэшбэк':{amount:30},'Промобонусы':{amount:40}});
assert.deepEqual(ads,{paid:'120.10',bonus:'70.00',unknown:[]});
const f={forPay:'1000.00',retailAmount:'1200.10',deliveryService:100,paidStorage:10,paidAcceptance:20,penalty:5,deduction:150,cashbackAmount:-9,cashbackCommissionChange:2,cashbackDiscount:25,rebillLogisticCost:999,acquiringFee:50,additionalPayment:10,advertisingDeductions:100};
const settings={operational_expenses:'20.10',external_promotion_expenses:'30.20'};
const e=economy(f,'200.00',settings,'0.00',ads,'5.00','2000.00',true);
assert.equal(e.payout,'737.00');
assert.equal(e.tax,'60.01');
assert.equal(e.advertising_total,'150.30');
assert.equal(e.net_profit,'406.59','net negative refunds, add loyalty compensation; acquiring/rebill not deducted twice; remuneration correction and advertising charged once');
assert.equal(e.drr_orders,7.515);
assert.equal(e.reconciliation_required,undefined);
assert.equal(economy(f,null,settings,'0',ads,5,2000,true).net_profit,null);
assert.equal(economy(f,'200',settings,null,ads,5,2000,true).net_profit,null);
assert.equal(economy(f,'200',settings,'0',ads,5,2000,false).net_profit,null);
assert.equal(economy(f,'200',settings,'0',advertising({'new':{amount:1}}),5,2000,true).net_profit,null);
assert.equal(economy(f,'200',settings,'0',ads,5,2000,true,1).drr_orders,null);
assert.equal(economy({...f,retailAmount:-100},'200',settings,'0',ads,5,0,true).tax,'-5.00');
assert.equal(economy(f,'200',settings,'0',ads,'0.01',0,true).tax,'0.12');
console.log('API economy: refunds, compensation, money/bonus ads, tax rounding, no double deduction, incomplete inputs passed.');
