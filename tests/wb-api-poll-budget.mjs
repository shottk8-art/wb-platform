import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const elements=new Map(),calls=[],listeners={};let timer,revision='unchanged';
const el=id=>{if(!elements.has(id))elements.set(id,{value:'',dataset:{},addEventListener(){}});return elements.get(id);};
const cabinet={complete:true,job:{id:'same',status:'complete',updated_at:'2026-10-10T12:00:00Z'},shop:{tax_rate:0},settings:{},sources:{orders:{status:'downloaded'},ads:{status:'downloaded',totals:{}},media:{status:'downloaded',amount:'0.00'}},finance:{},products:[]};
const document={hidden:false,getElementById:el,addEventListener:(key,fn)=>listeners[key]=fn};
const window={WBApi:{cabinet:async(action)=>{calls.push(action);return {cabinet,trend:[],revision,history_loading:true};}}};
vm.runInNewContext(readFileSync(new URL('../assets/wb-api-cabinet.js',import.meta.url),'utf8'),{window,document,Date,Intl,Map,Set,setTimeout:fn=>{timer=fn;return 1;},clearTimeout:()=>{timer=null;}});
let changes=0;window.WBApiCabinet.subscribe(()=>{changes++;window.WBApiCabinet.overview();});
const tick=()=>new Promise(resolve=>setImmediate(resolve));
window.WBApiCabinet.setContext({shopId:'synthetic',allowed:true});await tick();
assert.equal(calls.filter(c=>c==='cabinet_trend').length,1);
const statusText=el('apiCabinetStatus').textContent;
timer();await tick();
assert.equal(calls.at(-1),'cabinet_status');assert.equal(changes,1);
assert.equal(el('apiCabinetStatus').textContent,statusText,'unchanged status must not leave a permanent reading message');
assert.equal(calls.filter(c=>c==='cabinet_trend').length,1,'unchanged status cannot reread/reanimate history');
revision='new-completed-month';timer();await tick();assert.equal(changes,2);
assert.equal(calls.filter(c=>c==='cabinet_trend').length,2,'new data must update the overview');
document.hidden=true;listeners.visibilitychange();assert.equal(timer,null,'hidden tabs stop polling');
document.hidden=false;listeners.visibilitychange();await tick();assert.equal(calls.at(-1),'cabinet_status');
window.WBApiCabinet.setContext({shopId:'other',allowed:false});assert.equal(timer,null);
console.log('Poll budget: passed (unchanged data cached, changed revision refreshed, hidden tabs paused, shop isolation).');
