const assert=require('node:assert/strict');
const {create,KEY,TTL}=require('../assets/onboarding-draft.js');
let time=Date.parse('2026-10-21T12:00:00Z');
const values=new Map(),storage={getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k)};
const draft=create(storage,()=>time);
assert.equal(draft.read(),null);
assert.equal(draft.save({name:'  Новый бренд  ',marketplace:'ozon',planId:'team'}),true);
assert.equal(draft.read().name,'Новый бренд');
assert.equal(draft.read('other-user'),null,'anonymous choices cannot prefill an arbitrary account');
assert.equal(draft.bind('confirmed-user'),true);
assert.equal(draft.read(),null,'bound drafts are not guest drafts');
assert.equal(draft.read('confirmed-user').planId,'team');
assert.equal(create(storage,()=>time).read('confirmed-user').name,'Новый бренд','choices survive the auth redirect');
assert.equal(draft.read('confirmed-user').marketplace,undefined,'onboarding no longer constrains the shop to one marketplace');
assert.equal(draft.read('other-user'),null);
assert.equal(draft.bind('other-user'),false,'cannot rebind a draft to another account');
draft.clear('other-user');assert(draft.read('confirmed-user'));
draft.clear('confirmed-user');assert.equal(values.has(KEY),false);
assert.equal(draft.save({name:'Store',marketplace:'wildberries',planId:'invented'}),false);
assert.equal(draft.save({name:' ',marketplace:'wildberries',planId:null}),false);
draft.save({name:'Store',marketplace:'wildberries',planId:null});time+=TTL+1;
assert.equal(draft.read(),null,'expired draft is never reused');
values.set(KEY,'{');assert.equal(draft.read(),null,'corrupt storage is recoverable');
const blocked=create({getItem(){throw Error();},setItem(){throw Error();},removeItem(){throw Error();}},()=>time);
assert.equal(blocked.save({name:'Private mode',marketplace:'ozon',planId:null}),true);
assert.equal(blocked.persistent,false);assert.equal(blocked.read().name,'Private mode');
assert.equal(blocked.bind('confirmed-user'),true);assert(blocked.read('confirmed-user'));
time+=TTL+1;assert.equal(blocked.read('confirmed-user'),null,'private-mode fallback also expires');
values.set(KEY,JSON.stringify({version:1,name:'Injected',marketplace:'ozon',planId:'team',userId:'confirmed-user',at:time,role:'admin',access_token:'not-a-token'}));
assert.deepEqual(Object.keys(create(storage,()=>time).read('confirmed-user')).sort(),['at','name','planId','userId','version'],'legacy marketplace selections and injected fields are ignored');
console.log('Onboarding draft: PASS (redirect persistence, confirmed-user binding, expiry, validation, private-mode fallback).');
