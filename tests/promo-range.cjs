const assert=require('node:assert/strict');
const range=require('../assets/promo-range.js');
assert.equal(range.parse('29.02.2024'),'2024-02-29');
for(const value of ['29.02.2025','31.04.2026','00.11.2026','12.13.2026','2026-11-18','1.2.2026'])assert.equal(range.parse(value),null);
assert.equal(range.display('2026-11-18'),'18.11.2026');
assert.equal(range.formatInput('18112026'),'18.11.2026','numeric phone input adds separators');
assert.equal(range.formatInput('18/11/2026'),'18.11.2026','pasted date accepts separators');
assert.equal(range.formatInput('18.11.2026'),'18.11.2026');
assert.equal(range.formatInput('18.'),'18','backspace can remove a separator');
assert.equal(range.formatInput('181'),'18.1','partial entry stays editable');
assert.equal(range.formatInput(''),'');
assert.equal(range.parse(range.formatInput('31042026')),null,'formatting never accepts an impossible date');
assert.equal(range.length('2026-10-31','2026-11-01'),2);
assert.equal(range.length('2024-02-28','2024-03-01'),3);
assert.equal(range.last(range.serial('2024-02-01')),'2024-02-29');
assert.equal(range.last(range.serial('2026-12-01')),'2026-12-31');
assert.equal(range.first(range.serial('2026-12-01')+1),'2027-01-01');
const min='2025-12-01',max='2026-11-18';
assert.deepEqual(range.preset('7',min,max),{from:'2026-11-12',to:max});
assert.deepEqual(range.preset('30',min,max),{from:'2026-10-20',to:max});
assert.deepEqual(range.preset('previous',min,max),{from:'2026-10-01',to:'2026-10-31'});
assert.deepEqual(range.preset('current',min,max),{from:'2026-11-01',to:max});
assert.deepEqual(range.preset('30','2026-11-15',max),{from:'2026-11-15',to:max},'shortcuts respect available history');
assert.equal(range.error('2026-11-18',max,min,max),'');
assert.match(range.error('2026-11-19','2026-11-18',min,max),/Начало/);
assert.match(range.error('2025-11-30','2026-11-18',min,max),/Доступны/);
assert.match(range.error('2026-11-01','2026-11-19',min,max),/Доступны/);
assert.match(range.error('2026-02-30','2026-03-01',min,max),/формате/);
console.log('Promo range PASS: numeric phone entry, pasted dates, leap days, strict input, inclusive UTC days, year boundaries, shortcuts, history/future limits and inverted ranges.');
