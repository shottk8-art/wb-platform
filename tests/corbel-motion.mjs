import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../assets/corbel-motion.js',import.meta.url),'utf8');
let reduced=false;
const animations=[];
const node={getClientRects:()=>[],animate(frames,options){
  let resolve,reject;
  const finished=new Promise((a,b)=>{resolve=a;reject=b});
  const animation={frames,options,finished,playState:'running',cancel(){this.cancelled=true;this.playState='idle';reject(Error('cancelled'))},finish(){this.playState='finished';resolve()}};
  animations.push(animation);return animation;
}};
const shell={};
const context={window:{WBShell:shell,matchMedia:()=>({matches:reduced})},document:{documentElement:{},readyState:'loading',addEventListener(){},querySelectorAll:s=>s==='.app-view.is-active'?[node]:[],getElementById:()=>null,querySelector:()=>null,getAnimations:()=>animations},WeakMap,Map,Promise};
vm.runInNewContext(source,context);
const tick=()=>new Promise(resolve=>setImmediate(resolve));
const commits=[];
shell.motion.navigate(()=>commits.push('obsolete'));
shell.motion.navigate(()=>commits.push('latest'));
animations.at(-1).finish();await tick();
assert.deepEqual(commits,['latest'],'rapid navigation commits only latest route');
assert.equal(animations[1].cancelled,true,'completed forwards exit must be cancelled, not just forgotten');
shell.motion.navigate(()=>commits.push('cancelled-by-current-view'));
shell.motion.enter('overview');await tick();
assert.deepEqual(commits,['latest'],'returning to current route cancels the queued route');
reduced=true;shell.motion.navigate(()=>commits.push('reduced'));
assert.deepEqual(commits,['latest','reduced']);
let themed=false;shell.motion.theme('dark',null,()=>themed=true);assert.ok(themed,'reduced motion applies appearance immediately');
reduced=false;themed=false;shell.motion.theme('light',null,()=>themed=true);assert.ok(themed,'unsupported View Transitions uses immediate fallback');
assert.equal(animations[0].options.duration,200,'Corbel exit duration');
const modal={hidden:false,querySelector:()=>node};
shell.motion.hideModal(modal);animations.at(-1).finish();await tick();
assert.equal(modal.hidden,true,'completed modal close hides the form');
assert.equal(animations.at(-1).cancelled,true,'completed modal exit is removed before reopening');
modal.hidden=false;shell.motion.hideModal(modal);reduced=true;shell.motion.settleReducedMotion();await tick();
assert.equal(modal.hidden,true,'enabling reduced motion completes an in-progress modal close');
for(const page of ['app.html','index.html','admin.html'])assert.match(readFileSync(new URL('../'+page,import.meta.url),'utf8'),/corbel-motion\.js/);
assert.doesNotMatch(source,/\bfetch\s*\(|supabase|\.from\s*\(/,'motion cannot issue financial/auth queries');
console.log('Motion: PASS (interruptions, last click wins, current-route cancellation, reduced motion, View Transition fallback, all surfaces, no network).');
