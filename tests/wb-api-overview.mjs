import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const html=readFileSync(new URL('../app.html',import.meta.url),'utf8');
assert.doesNotMatch(html,/API · тест|Личный тест|тестовое подключение|wbApiPreviewBtn|wbApiHistoryBtn/);
assert.match(html,/id="secApiCabinet" data-view="overview"/);
assert.match(html,/saveTaxBtn[\s\S]*?WBApiCabinet\?\.reload/);
assert.match(html,/saveCostPrice[\s\S]*?WBApiCabinet\?\.reload/);
const elements=new Map();
const el=id=>{if(!elements.has(id)) elements.set(id,{hidden:false,textContent:'',parentElement:{hidden:false}});return elements.get(id);};
const source=html.slice(html.indexOf("  function updateOverviewSource()"),html.indexOf('  function toast('));
const state={document:{getElementById:el,querySelectorAll:()=>[]},shop:{id:'green'},activeView:'overview',overviewSource:'files',sourceShopId:null,aiAllowed:true,allowed:true};
state.apiCabinetAllowed=()=>state.allowed;
vm.createContext(state); vm.runInContext(source,state);
state.updateOverviewSource();
assert.equal(state.overviewSource,'api','GREEN FLOW opens API results in the ordinary Overview');
assert.equal(el('secApiCabinet').hidden,false);
assert.equal(el('secKpis').hidden,true);
assert.equal(el('secAiAnalysis').hidden,true,'file-only AI must not analyze a different data source');
assert.equal(el('periodSelect').parentElement.hidden,true);
state.overviewSource='files'; state.updateOverviewSource();
assert.equal(el('secApiCabinet').hidden,true);
assert.equal(el('secKpis').hidden,false);
assert.equal(el('secAiAnalysis').hidden,false);
state.allowed=false; state.shop={id:'other'}; state.updateOverviewSource();
assert.equal(el('overviewSource').hidden,true);
assert.equal(el('secApiCabinet').hidden,true);
assert.equal(state.overviewSource,'files','other shop does not inherit API mode or data');
console.log('API overview: passed (no test UI, source separation, private gate, costs/tax invalidation).');
