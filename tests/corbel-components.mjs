import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const root=new URL('../',import.meta.url),window={};
vm.runInNewContext(readFileSync(new URL('assets/dashboard.js',root),'utf8'),{window,document:{},Intl,Map,Date});
const mini=window.WBDashboard.kpiSparkline;
assert.equal(mini([], 'sales'),'');
assert.equal(mini([{sales:10}], 'sales'),'','single month is not fabricated into a trend');
assert.equal(mini([{sales:null},{sales:10}], 'sales'),'');
assert.equal(mini([{sales:false},{sales:' '},{sales:10}], 'sales'),'','missing/invalid inputs cannot become zeroes');
const negative=mini([{sales:-10},{sales:0},{sales:20}], 'sales');
assert.match(negative,/M4.00,36.00 L40.00,26.67 L76.00,8.00/);
const gaps=mini([{sales:10},{sales:null},{sales:20}], 'sales');
assert.equal((gaps.match(/M\d/g)||[]).length,2,'missing months split the trace');
assert.doesNotMatch(gaps,/NaN|undefined/);
const bars=mini([{quantity:0},{quantity:5},{quantity:null},{quantity:9}], 'quantity');
assert.equal((bars.match(/<rect /g)||[]).length,3,'bars use only available months');
assert.match(bars,/kpi-mini-bars/);
assert.match(mini([{sales:12},{sales:12}], 'sales'),/M4.00,22.00 L76.00,22.00/);
const many=mini(Array.from({length:50},(_,sales)=>({sales})), 'sales');
assert.equal((many.match(/[ML]\d/g)||[]).length,12,'render budget is twelve loaded months');
const source=readFileSync(new URL('assets/corbel-components.js',root),'utf8');
assert.match(source,/dispatchEvent\(new Event\('change'/,'original change path is kept');
assert.match(source,/dispatchEvent\(new Event\('input'/);
assert.match(source,/option\.disabled/);assert.match(source,/option\.hidden/);
assert.match(source,/e\.key === 'Escape'/);assert.match(source,/e\.key === 'Tab'/);
assert.doesNotMatch(source,/\bfetch\s*\(|supabase|\.from\s*\(/,'presentation has no data-service access');
for(const page of ['app.html','index.html','admin.html'])assert.match(readFileSync(new URL(page,root),'utf8'),/corbel-components\.js/);
console.log('Components: PASS (real history, negative/flat/missing values, bounded SVG, shared source-select change path, no network).');
